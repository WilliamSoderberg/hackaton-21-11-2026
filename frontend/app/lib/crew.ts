import data from "../crew/incidents.json";

// Urgency levels from the classification guide (data/classification_guide.md).
export type UrgencyLevel = "A" | "B" | "C" | "D" | "E";

export type LatLng = { lat: number; lng: number };

export type RedFlag = {
  label: string;
  quote: string; // exact words from the call
  time: string; // mm:ss into the call
  t: number;
  speaker: "caller" | "operator";
  call_id: string;
};

export type Hospital = LatLng & { name: string; detail: string };

export type UrgencyStep = { t: number; time: string; urgency: UrgencyLevel };

type IncidentBase = {
  incident_id: string;
  title: string;
  calls: { call_id: string; title: string; minutes_since_call: number; urgency_timeline: UrgencyStep[] }[];
  category: string;
  category_name: string;
  urgency: UrgencyLevel;
  urgency_name: string;
  address: string;
  scene: LatLng;
  minutes_since_call: number; // synthetic, at page load
  note?: string;
  extra_units: string[];
  prepare_en_route: string[];
  bring: string[];
  key_facts: string[];
  scene_notes: string[];
  open_questions: string[];
  red_flags: RedFlag[];
  handover: string[];
};

// What the ambulance crew gets at dispatch: the crew_briefing gold label of
// each call, merged per incident, plus synthetic map positions in Lund.
// "pending" = ambulance not decided yet (nurse call-back).
export type CrewIncident = IncidentBase & {
  dispatch: "dispatched" | "pending";
  unit: string;
  ambulance_position: LatLng;
  destination_hospital: Hospital;
  destination: string;
  pre_alert: string;
  crew: string;
  lights_and_sirens: boolean;
};

// A call that got advice only (no crew_briefing).
export type AdviceIncident = IncidentBase & {
  dispatch: "none";
  unit: null;
  ambulance_position: null;
  destination_hospital: null;
  destination: null;
  pre_alert: null;
  crew: null;
  lights_and_sirens: false;
};

export type Incident = CrewIncident | AdviceIncident;

