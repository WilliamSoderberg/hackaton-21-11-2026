// `python data/source/build.py` into app/crew/incidents.json.
export const allIncidents = data.incidents as Incident[];
export const crewIncidents = allIncidents.filter((i): i is CrewIncident => i.dispatch !== "none");

export const hospitals: Hospital[] = [
  ...new Map(crewIncidents.map((i) => [i.destination_hospital.name, i.destination_hospital])).values(),
];

export function distanceKm(a: LatLng, b: LatLng) {
  const rad = Math.PI / 180;
  const dLat = (b.lat - a.lat) * rad;
  const dLng = (b.lng - a.lng) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

// Rough drive time when no road route is available: straight line × 1.35 for
// roads, 65 km/h average with lights and sirens, 45 km/h without.
export function estimateMinutes(a: LatLng, b: LatLng, lightsAndSirens: boolean) {
  return (distanceKm(a, b) * 1.35 * 60) / (lightsAndSirens ? 65 : 45);
}
