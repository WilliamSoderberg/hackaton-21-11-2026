// Scores the dashboard's current keyword classifier (frontend/app/lib/calls.ts)
// against the synthetic gold labels. Run from repo root:
//   python3 data/source/build.py && node --experimental-strip-types data/eval/eval_keyword_baseline.ts
// Use the same loop to score a Claude-based classifier later: swap classify() for your function.
import { readFileSync, writeFileSync } from "node:fs";
import { classify } from "../../frontend/app/lib/calls.ts";

const ORDER = ["Low", "Medium", "High", "Critical"];
const rows = readFileSync("data/calls/all_calls.jsonl", "utf8").trim().split("\n").map((l) => JSON.parse(l));

let urgExact = 0, urgUnder = 0, amb = 0, ambN = 0, typeOk = 0, flagN = 0;
const out: string[] = ["| Call | Gold urgency | Keyword urgency | Gold ambulance | Keyword ambulance | Gold type | Keyword physical/mental % | Indicators |", "|---|---|---|---|---|---|---|---|"];
for (const r of rows) {
  const lines = r.transcript.map((t: any) => ({ speaker: t.speaker === "operator" ? "Operator" : "Caller", text: t.text }));
  const c = classify(lines);
  const g = r.gold_label.dashboard;
  const d = ORDER.indexOf(c.urgency) - ORDER.indexOf(g.urgency);
  if (d === 0) urgExact++;
  if (d < 0) urgUnder++;
  if (g.ambulance !== null) { ambN++; if (c.ambulance === g.ambulance) amb++; }
  const kwType = c.indicators.length === 0 ? "none" : c.mental >= 30 && c.physical >= 30 ? "both" : c.mental > c.physical ? "mental" : "physical";
  if (kwType === g.type) typeOk++;
  out.push(`| ${r.call_id} | ${g.urgency} | ${c.urgency}${d < 0 ? " ⚠️ under" : d > 0 ? " (over)" : ""} | ${g.ambulance} | ${c.ambulance} | ${g.type} | ${c.physical}/${c.mental} | ${c.indicators.join(", ") || "-"} |`);
  flagN += r.gold_label.red_flags.length;
}
const n = rows.length;
const summary = `Keyword baseline on ${n} synthetic calls: urgency exact ${urgExact}/${n}, UNDER-triaged ${urgUnder}/${n}, ambulance ${amb}/${ambN}, physical/mental type ${typeOk}/${n}. Red flags with exact quotes: 0/${flagN} (keyword model gives no quotes).`;
console.log(summary + "\n\n" + out.join("\n"));
writeFileSync("data/eval/keyword_baseline_results.md", `# Keyword baseline results\n\n> Synthetic data. Generated by eval_keyword_baseline.ts.\n\n${summary}\n\n${out.join("\n")}\n`);
