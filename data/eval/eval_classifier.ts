// Scores the triage backend (POST /api/classify, backend/src/main.rs) against the synthetic gold labels.
// Works for both modes: keyword fallback (no ANTHROPIC_API_KEY) and Claude (key set) -> "before" vs "after".
// Run from repo root, with the backend running (cd backend && cargo run):
//   python3 data/source/build.py
//   node data/eval/eval_classifier.ts            (Node 23+; on Node 22 add --experimental-strip-types)
// Optional: BACKEND_URL=http://localhost:8080
import { readFileSync, writeFileSync } from "node:fs";

const BACKEND_URL = process.env.BACKEND_URL ?? "http://localhost:8080";
const ORDER = ["Low", "Medium", "High", "Critical"];
const rows = readFileSync("data/calls/all_calls.jsonl", "utf8").trim().split("\n").map((l) => JSON.parse(l));

let urgExact = 0, urgUnder = 0, amb = 0, ambN = 0, typeOk = 0, flagHit = 0, flagN = 0;
const sources = new Set<string>();
const out: string[] = [
  "| Call | Gold urgency | Model urgency | Gold ambulance | Model ambulance | Gold type | Model physical/mental % | Indicators |",
  "|---|---|---|---|---|---|---|---|",
];

for (const r of rows) {
  const lines = r.transcript.map((t: any) => ({ speaker: t.speaker === "operator" ? "Operator" : "Caller", text: t.text }));
  const res = await fetch(`${BACKEND_URL}/api/classify`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ lines }),
  });
  if (!res.ok) throw new Error(`${r.call_id}: backend returned ${res.status}`);
  const c = await res.json();
  sources.add(`${c.sources?.triage}/${c.sources?.indicators}`);
  const g = r.gold_label.dashboard;
  const d = ORDER.indexOf(c.urgency) - ORDER.indexOf(g.urgency);
  if (d === 0) urgExact++;
  if (d < 0) urgUnder++;
  if (g.ambulance !== null) { ambN++; if (c.ambulance === g.ambulance) amb++; }
  const type = c.indicators.length === 0 ? "none" : c.mental >= 30 && c.physical >= 30 ? "both" : c.mental > c.physical ? "mental" : "physical";
  if (type === g.type) typeOk++;
  // Rough red-flag recall: a gold flag counts as found if any indicator label shares a word (4+ letters) with it.
  const words = (s: string) => new Set(s.toLowerCase().match(/[a-z]{4,}/g) ?? []);
  const ind = c.indicators.map(words);
  for (const f of r.gold_label.red_flags) {
    flagN++;
    const fw = words(f.label + " " + f.quote);
    if (ind.some((w: Set<string>) => [...w].some((x) => fw.has(x)))) flagHit++;
  }
  out.push(`| ${r.call_id} | ${g.urgency} | ${c.urgency}${d < 0 ? " ⚠️ under" : d > 0 ? " (over)" : ""} | ${g.ambulance} | ${c.ambulance} | ${g.type} | ${c.physical}/${c.mental} | ${c.indicators.join(", ") || "-"} |`);
}

const n = rows.length;
const summary = `Model sources (triage/indicators): ${[...sources].join(", ")}. On ${n} synthetic calls: urgency exact ${urgExact}/${n}, UNDER-triaged ${urgUnder}/${n}, ambulance ${amb}/${ambN}, physical/mental type ${typeOk}/${n}, red flags matched by an indicator ~${flagHit}/${flagN}.`;
console.log(summary + "\n\n" + out.join("\n"));
const tag = [...sources].every((s) => s.startsWith("claude")) ? "claude" : "keyword";
writeFileSync(`data/eval/results_${tag}.md`, `# Classifier eval (${tag})\n\n> Synthetic data. Generated by data/eval/eval_classifier.ts on ${new Date().toISOString()}.\n\n${summary}\n\n${out.join("\n")}\n`);
